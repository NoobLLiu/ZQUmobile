/// 按 skill 规则的时段对照表取问候语。
String autoGreeting(DateTime now) {
  final h = now.hour;
  if (h >= 5 && h <= 8) return '早上好[太阳]';
  if (h >= 9 && h <= 11) return '上午好[太阳]';
  if (h >= 12 && h <= 13) return '中午好[太阳]';
  if (h >= 14 && h <= 16) return '下午好[太阳]';
  if (h >= 17 && h <= 18) return '傍晚好🌇';
  return '晚上好🌙';
}

/// 拼接整句问候：称谓 + 问候语（含表情）。
String buildGreetingLine(String salutation, String greeting) {
  final s = salutation.isEmpty ? '各位同学' : salutation;
  return s + greeting;
}

/// 组装一次转写请求的用户消息。
String buildUserMessage({
  required int sourceModeIndex,
  required String source,
  required String target,
  required int deadlineModeIndex,
  required String newDeadline,
  required List<NoticeExtra> extras,
  required String greeting,
  required String original,
}) {
  final mode = kSourceModes[sourceModeIndex];
  String sourceLine;
  if (mode.key == 'custom') {
    sourceLine = '消息来源模式：具体来源名（${source.trim()}）';
  } else if (mode.key == 'forward') {
    sourceLine = '消息来源模式：只显示“转发”二字（标题行不出现来源名）';
  } else {
    sourceLine = '消息来源模式：无（标题行连“转发”二字也不出现）';
  }

  final greetingLine = buildGreetingLine(target, greeting);

  var deadlineLine = '截止时间：保持原样';
  if (deadlineModeIndex == 1) {
    deadlineLine = '截止时间：统一替换为 ${newDeadline.trim()}';
  }

  final lines = <String>[
    sourceLine,
    '问好对象：$target',
    '问好时间：$greeting',
    '整句问候（照此写，不要加标点）：$greetingLine',
    deadlineLine,
  ];

  final valid = extras
      .where((it) => it.text.trim().isNotEmpty)
      .toList(growable: false);
  if (valid.isNotEmpty) {
    lines.add('补充通知（${valid.length} 条）：');
    for (var i = 0; i < valid.length; i++) {
      final m = kExtraModes[valid[i].modeIndex];
      lines.add('第 ${i + 1} 条补充通知（处理方式：${m.label}）：${m.hint}');
      lines.add('【补充通知${i + 1}开始】');
      lines.add(valid[i].text.trim());
      lines.add('【补充通知${i + 1}结束】');
    }
  } else {
    lines.add('补充通知：无');
  }

  lines.add('');
  lines.add('原通知如下（【原通知开始】【原通知结束】两行是边界标记，不属于通知内容，不要出现在转写结果中）：');
  lines.add('【原通知开始】');
  lines.add(original);
  lines.add('【原通知结束】');

  return lines.join('\n');
}
