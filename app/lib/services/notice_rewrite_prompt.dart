/// 问好时间选项（`value` 为空表示按当前时间自动取）。
class GreetingOption {
  const GreetingOption(this.key, this.label, this.value);

  final String key;
  final String label;
  final String value;
}

/// 问好对象（称谓）选项。
class GreetingTarget {
  const GreetingTarget(this.key, this.label, this.salutation);

  final String key;
  final String label;

  /// 问候行里实际使用的称谓。
  final String salutation;
}

/// 消息来源模式：决定标题行怎么写。
class SourceMode {
  const SourceMode(this.key, this.label, this.hint);

  final String key;
  final String label;
  final String hint;
}

/// 截止时间处理方式。
class DeadlineMode {
  const DeadlineMode(this.key, this.label, this.hint);

  final String key;
  final String label;
  final String hint;
}

/// 补充通知的处理方式。
class ExtraMode {
  const ExtraMode(this.key, this.label, this.hint);

  final String key;
  final String label;
  final String hint;
}

/// 一条补充通知。
class NoticeExtra {
  NoticeExtra({this.text = '', this.modeIndex = 0});

  String text;

  /// 对应 [kExtraModes] 的下标。
  int modeIndex;
}

